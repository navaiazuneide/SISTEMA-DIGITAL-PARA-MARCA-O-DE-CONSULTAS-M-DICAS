CREATE OR REPLACE VIEW VW_AGENDA_CONSULTAS AS
SELECT
    C.ID_CONSULTA,
    C.CODIGO_CONSULTA,
    C.DATA_CONSULTA,
    C.HORA_CONSULTA,
    C.ESTADO,
    C.TIPO,
    U.NUMERO_UTENTE,
    U.NOME_COMPLETO AS UTENTE,
    M.NOME_COMPLETO AS MEDICO,
    E.NOME AS ESPECIALIDADE,
    K.NUMERO AS CONSULTORIO
FROM CONSULTA C
JOIN UTENTE U ON U.ID_UTENTE = C.ID_UTENTE
JOIN MEDICO M ON M.ID_MEDICO = C.ID_MEDICO
JOIN ESPECIALIDADE E ON E.ID_ESPECIALIDADE = C.ID_ESPECIALIDADE
JOIN CONSULTORIO K ON K.ID_CONSULTORIO = C.ID_CONSULTORIO;

-- VIEW 2: Historico clinico dos utentes
CREATE OR REPLACE VIEW VW_HISTORICO_UTENTE AS
SELECT
    U.NUMERO_UTENTE,
    U.NOME_COMPLETO AS UTENTE,
    H.DATA_REGISTO,
    E.NOME AS ESPECIALIDADE,
    M.NOME_COMPLETO AS MEDICO,
    H.DIAGNOSTICO,
    H.DESCRICAO AS OBSERVACOES
FROM HISTORICO_CLINICO H
JOIN UTENTE U ON U.ID_UTENTE = H.ID_UTENTE
JOIN CONSULTA C ON C.ID_CONSULTA = H.ID_CONSULTA
JOIN MEDICO M ON M.ID_MEDICO = C.ID_MEDICO
JOIN ESPECIALIDADE E ON E.ID_ESPECIALIDADE = H.ID_ESPECIALIDADE;


