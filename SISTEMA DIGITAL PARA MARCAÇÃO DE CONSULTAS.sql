-- 10. HORARIO
-- As horas sao guardadas no formato HH24:MI (exemplo: 08:30).
-- A validacao abaixo evita depender de REGEXP_LIKE em CHECK.
CREATE TABLE HORARIO (
    ID_HORARIO NUMBER(10) NOT NULL,
    ID_MEDICO NUMBER(10) NOT NULL,
    DIA_SEMANA VARCHAR2(20) NOT NULL,
    HORA_INICIO VARCHAR2(5) NOT NULL,
    HORA_FIM VARCHAR2(5) NOT NULL,
    DURACAO_CONSULTA NUMBER(3) DEFAULT 30 NOT NULL,
    CONSTRAINT PK_HORARIO PRIMARY KEY (ID_HORARIO),
    CONSTRAINT FK_HORARIO_MEDICO FOREIGN KEY (ID_MEDICO)
        REFERENCES MEDICO (ID_MEDICO),
    CONSTRAINT UQ_HORARIO_MEDICO
        UNIQUE (ID_MEDICO, DIA_SEMANA, HORA_INICIO),
    CONSTRAINT CK_HORARIO_DIA CHECK
        (DIA_SEMANA IN ('SEGUNDA','TERCA','QUARTA','QUINTA',
                        'SEXTA','SABADO','DOMINGO')),
    CONSTRAINT CK_HORARIO_HI CHECK
        (LENGTH(HORA_INICIO) = 5
         AND SUBSTR(HORA_INICIO,3,1) = ':'
         AND SUBSTR(HORA_INICIO,1,2) BETWEEN '00' AND '23'
         AND SUBSTR(HORA_INICIO,4,2) BETWEEN '00' AND '59'),
    CONSTRAINT CK_HORARIO_HF CHECK
        (LENGTH(HORA_FIM) = 5
         AND SUBSTR(HORA_FIM,3,1) = ':'
         AND SUBSTR(HORA_FIM,1,2) BETWEEN '00' AND '23'
         AND SUBSTR(HORA_FIM,4,2) BETWEEN '00' AND '59'),
    CONSTRAINT CK_HORARIO_ORDEM CHECK (HORA_FIM > HORA_INICIO),
    CONSTRAINT CK_HORARIO_DUR CHECK (DURACAO_CONSULTA > 0)
);

