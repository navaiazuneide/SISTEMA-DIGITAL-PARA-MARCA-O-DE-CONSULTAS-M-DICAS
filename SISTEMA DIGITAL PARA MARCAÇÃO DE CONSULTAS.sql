-- 12. CONSULTA
CREATE TABLE CONSULTA (
    ID_CONSULTA NUMBER(10) NOT NULL,
    CODIGO_CONSULTA VARCHAR2(20) NOT NULL,
    ID_UTENTE NUMBER(10) NOT NULL,
    ID_MEDICO NUMBER(10) NOT NULL,
    ID_ESPECIALIDADE NUMBER(10) NOT NULL,
    ID_CONSULTORIO NUMBER(10) NOT NULL,
    ID_UTILIZADOR NUMBER(10) NOT NULL,
    MARCADO_POR VARCHAR2(15) NOT NULL,
    DATA_CONSULTA DATE NOT NULL,
    HORA_CONSULTA VARCHAR2(5) NOT NULL,
    MOTIVO VARCHAR2(255) NOT NULL,
    TIPO VARCHAR2(20) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'MARCADA' NOT NULL,
    DATA_MARCACAO DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_CONSULTA PRIMARY KEY (ID_CONSULTA),
    CONSTRAINT UQ_CONSULTA_CODIGO UNIQUE (CODIGO_CONSULTA),

    CONSTRAINT FK_CONSULTA_UTENTE FOREIGN KEY (ID_UTENTE)
        REFERENCES UTENTE (ID_UTENTE),
    CONSTRAINT FK_CONSULTA_MEDICO FOREIGN KEY (ID_MEDICO)
        REFERENCES MEDICO (ID_MEDICO),
    CONSTRAINT FK_CONSULTA_ESPECIALIDADE FOREIGN KEY (ID_ESPECIALIDADE)
        REFERENCES ESPECIALIDADE (ID_ESPECIALIDADE),
    CONSTRAINT FK_CONSULTA_CONSULTORIO FOREIGN KEY (ID_CONSULTORIO)
        REFERENCES CONSULTORIO (ID_CONSULTORIO),
    CONSTRAINT FK_CONSULTA_UTILIZADOR FOREIGN KEY (ID_UTILIZADOR)
        REFERENCES UTILIZADOR (ID_UTILIZADOR),

    -- Garante que o medico esta associado a especialidade escolhida.
    CONSTRAINT FK_CONSULTA_MED_ESP
        FOREIGN KEY (ID_MEDICO, ID_ESPECIALIDADE)
        REFERENCES MEDICO_ESPECIALIDADE (ID_MEDICO, ID_ESPECIALIDADE),

    -- Garante que o consultorio atende a especialidade escolhida.
    CONSTRAINT FK_CONSULTA_CONS_ESP
        FOREIGN KEY (ID_CONSULTORIO, ID_ESPECIALIDADE)
        REFERENCES CONSULTORIO_ESPECIALIDADE
            (ID_CONSULTORIO, ID_ESPECIALIDADE),

    CONSTRAINT CK_CONSULTA_MARCADO CHECK
        (MARCADO_POR IN ('UTENTE','RESPONSAVEL','RECEPCIONISTA')),
    CONSTRAINT CK_CONSULTA_TIPO CHECK
        (TIPO IN ('PRIMEIRA','SEGUIMENTO','URGENCIA')),
    CONSTRAINT CK_CONSULTA_ESTADO CHECK
        (ESTADO IN ('MARCADA','CONFIRMADA','REALIZADA',
                    'CANCELADA','NAO_COMPARECEU','REAGENDADA')),
    CONSTRAINT CK_CONSULTA_DATA CHECK
        (DATA_CONSULTA = TRUNC(DATA_CONSULTA)),
    CONSTRAINT CK_CONSULTA_HORA CHECK
        (LENGTH(HORA_CONSULTA) = 5
         AND SUBSTR(HORA_CONSULTA,3,1) = ':'
         AND SUBSTR(HORA_CONSULTA,1,2) BETWEEN '00' AND '23'
         AND SUBSTR(HORA_CONSULTA,4,2) BETWEEN '00' AND '59')
);

