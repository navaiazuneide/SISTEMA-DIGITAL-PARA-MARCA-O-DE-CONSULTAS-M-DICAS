-- ============================================================
-- PARTE 5 - IMPEDIR MARCACOES NO MESMO HORARIO PARA O MEDICO
-- Consultas canceladas ou reagendadas deixam de bloquear o horario.
-- O formato HH24:MI permite comparacao textual correcta.
-- ============================================================

CREATE UNIQUE INDEX UX_CONSULTA_MEDICO_SLOT
ON CONSULTA (
    CASE WHEN ESTADO NOT IN ('CANCELADA','REAGENDADA')
         THEN ID_MEDICO END,
    CASE WHEN ESTADO NOT IN ('CANCELADA','REAGENDADA')
         THEN DATA_CONSULTA END,
    CASE WHEN ESTADO NOT IN ('CANCELADA','REAGENDADA')
         THEN HORA_CONSULTA END
);


