-- 1. Listar todos os utentes.
SELECT * FROM UTENTE;

-- 2. Listar todos os medicos.
SELECT * FROM MEDICO;

-- 3. Listar todas as especialidades.
SELECT * FROM ESPECIALIDADE;

-- 4. Listar todos os consultorios.
SELECT * FROM CONSULTORIO;

-- 5. Consultar medicos e respectivas especialidades.
SELECT
    M.NOME_COMPLETO AS MEDICO,
    E.NOME AS ESPECIALIDADE
FROM MEDICO M
JOIN MEDICO_ESPECIALIDADE ME
    ON M.ID_MEDICO = ME.ID_MEDICO
JOIN ESPECIALIDADE E
    ON ME.ID_ESPECIALIDADE = E.ID_ESPECIALIDADE
ORDER BY M.NOME_COMPLETO;

-- 6. Consultar os consultorios e as especialidades atendidas.
SELECT
    K.NUMERO AS CONSULTORIO,
    K.LOCALIZACAO,
    E.NOME AS ESPECIALIDADE
FROM CONSULTORIO K
JOIN CONSULTORIO_ESPECIALIDADE CE
    ON K.ID_CONSULTORIO = CE.ID_CONSULTORIO
JOIN ESPECIALIDADE E
    ON CE.ID_ESPECIALIDADE = E.ID_ESPECIALIDADE
ORDER BY K.NUMERO;

-- 7. Consultar a agenda completa.
SELECT * FROM VW_AGENDA_CONSULTAS
ORDER BY DATA_CONSULTA, HORA_CONSULTA;

-- 8. Consultar o historico clinico.
SELECT * FROM VW_HISTORICO_UTENTE
ORDER BY DATA_REGISTO DESC;

-- 9. Contar consultas por estado.
SELECT
    ESTADO,
    COUNT(*) AS TOTAL_CONSULTAS
FROM CONSULTA
GROUP BY ESTADO
ORDER BY ESTADO;

-- 10. Contar consultas por especialidade, incluindo especialidades sem consultas.
SELECT
    E.NOME AS ESPECIALIDADE,
    COUNT(C.ID_CONSULTA) AS TOTAL_CONSULTAS
FROM ESPECIALIDADE E
LEFT JOIN CONSULTA C
    ON C.ID_ESPECIALIDADE = E.ID_ESPECIALIDADE
GROUP BY E.NOME
ORDER BY E.NOME;

-- 11. Calcular o total de pagamentos efectuados.
SELECT
    NVL(SUM(VALOR), 0) AS TOTAL_RECEBIDO
FROM PAGAMENTO
WHERE ESTADO = 'PAGO';

-- 12. Calcular a media dos pagamentos.
SELECT
    NVL(ROUND(AVG(VALOR), 2), 0) AS MEDIA_PAGAMENTOS
FROM PAGAMENTO;

-- 13. Consultar as consultas de um utente especifico.
SELECT
    U.NOME_COMPLETO AS UTENTE,
    C.CODIGO_CONSULTA,
    C.DATA_CONSULTA,
    C.HORA_CONSULTA,
    C.ESTADO
FROM UTENTE U
JOIN CONSULTA C ON U.ID_UTENTE = C.ID_UTENTE
WHERE U.NUMERO_UTENTE = 'UT001'
ORDER BY C.DATA_CONSULTA;

-- 14. Consultar as consultas de um medico especifico.
SELECT
    M.NOME_COMPLETO AS MEDICO,
    C.CODIGO_CONSULTA,
    C.DATA_CONSULTA,
    C.HORA_CONSULTA,
    C.ESTADO
FROM MEDICO M
JOIN CONSULTA C ON M.ID_MEDICO = C.ID_MEDICO
WHERE M.CODIGO_MEDICO = 'MED001'
ORDER BY C.DATA_CONSULTA, C.HORA_CONSULTA;

-- 15. Listar consultas marcadas e confirmadas.
SELECT
    CODIGO_CONSULTA,
    DATA_CONSULTA,
    HORA_CONSULTA,
    ESTADO
FROM CONSULTA
WHERE ESTADO IN ('MARCADA','CONFIRMADA')
ORDER BY DATA_CONSULTA, HORA_CONSULTA;

-- 16. Consultar receitas, utentes, medicos e medicamentos.
SELECT
    R.CODIGO_RECEITA,
    U.NOME_COMPLETO AS UTENTE,
    M.NOME_COMPLETO AS MEDICO,
    MD.NOME AS MEDICAMENTO,
    RM.QUANTIDADE,
    RM.INSTRUCOES_UTILIZACAO
FROM RECEITA R
JOIN UTENTE U ON U.ID_UTENTE = R.ID_UTENTE
JOIN MEDICO M ON M.ID_MEDICO = R.ID_MEDICO
JOIN RECEITA_MEDICAMENTO RM ON RM.ID_RECEITA = R.ID_RECEITA
JOIN MEDICAMENTO MD ON MD.ID_MEDICAMENTO = RM.ID_MEDICAMENTO
ORDER BY R.CODIGO_RECEITA;

-- 17. Consultar pagamentos com dados da consulta e do utente.
SELECT
    P.CODIGO_PAGAMENTO,
    U.NOME_COMPLETO AS UTENTE,
    C.CODIGO_CONSULTA,
    P.VALOR,
    P.METODO,
    P.ESTADO
FROM PAGAMENTO P
JOIN CONSULTA C ON C.ID_CONSULTA = P.ID_CONSULTA
JOIN UTENTE U ON U.ID_UTENTE = C.ID_UTENTE
ORDER BY P.DATA_PAGAMENTO DESC;

-- 18. Consultar notificacoes enviadas.
SELECT
    N.CODIGO_NOTIFICACAO,
    C.CODIGO_CONSULTA,
    N.MENSAGEM,
    N.TIPO,
    N.DESTINATARIO,
    N.ESTADO
FROM NOTIFICACAO N
JOIN CONSULTA C ON C.ID_CONSULTA = N.ID_CONSULTA
ORDER BY N.DATA_ENVIO DESC;

-- 19. Contar o numero de utentes registados.
SELECT COUNT(*) AS TOTAL_UTENTES
FROM UTENTE;

-- 20. Contar o numero de medicos activos.
SELECT COUNT(*) AS TOTAL_MEDICOS_ACTIVOS
FROM MEDICO
WHERE ESTADO = 'A';

-- 21. Consultar os horarios dos medicos.
SELECT
    M.NOME_COMPLETO AS MEDICO,
    H.DIA_SEMANA,
    H.HORA_INICIO,
    H.HORA_FIM,
    H.DURACAO_CONSULTA
FROM HORARIO H
JOIN MEDICO M ON M.ID_MEDICO = H.ID_MEDICO
ORDER BY M.NOME_COMPLETO, H.DIA_SEMANA;

-- 22. Consultar os utentes e os respectivos responsaveis.
SELECT
    U.NOME_COMPLETO AS UTENTE,
    R.NOME_COMPLETO AS RESPONSAVEL,
    R.CONTACTO,
    UR.GRAU_PARENTESCO
FROM UTENTE_RESPONSAVEL UR
JOIN UTENTE U ON U.ID_UTENTE = UR.ID_UTENTE
JOIN RESPONSAVEL R ON R.ID_RESPONSAVEL = UR.ID_RESPONSAVEL
ORDER BY U.NOME_COMPLETO;

-- 23. Consultar o total pago por metodo de pagamento.
SELECT
    METODO,
    SUM(VALOR) AS TOTAL
FROM PAGAMENTO
WHERE ESTADO = 'PAGO'
GROUP BY METODO
ORDER BY METODO;

-- 24. Consultar especialidades com mais de zero consultas.
SELECT
    E.NOME AS ESPECIALIDADE,
    COUNT(C.ID_CONSULTA) AS TOTAL
FROM ESPECIALIDADE E
JOIN CONSULTA C ON C.ID_ESPECIALIDADE = E.ID_ESPECIALIDADE
GROUP BY E.NOME
HAVING COUNT(C.ID_CONSULTA) > 0
ORDER BY TOTAL DESC;

-- 25. Verificar se existem consultas sem atendimento.
SELECT
    C.CODIGO_CONSULTA,
    C.DATA_CONSULTA,
    C.ESTADO
FROM CONSULTA C
LEFT JOIN ATENDIMENTO A ON A.ID_CONSULTA = C.ID_CONSULTA
WHERE A.ID_ATENDIMENTO IS NULL;

-- 26. Consultar todos os medicamentos registados.
SELECT
    CODIGO_MEDICAMENTO,
    NOME,
    DESCRICAO,
    ESTADO
FROM MEDICAMENTO
ORDER BY NOME;

-- 27. Consultar consultas por intervalo de datas.
SELECT
    CODIGO_CONSULTA,
    DATA_CONSULTA,
    HORA_CONSULTA,
    ESTADO
FROM CONSULTA
WHERE DATA_CONSULTA BETWEEN DATE '2026-12-01' AND DATE '2026-12-31'
ORDER BY DATA_CONSULTA, HORA_CONSULTA;

-- 28. Consultar o valor total pendente.
SELECT
    NVL(SUM(VALOR), 0) AS TOTAL_PENDENTE
FROM PAGAMENTO
WHERE ESTADO = 'PENDENTE';

-- 29. Consultar os dados gerais das consultas realizadas.
SELECT
    C.CODIGO_CONSULTA,
    U.NOME_COMPLETO AS UTENTE,
    M.NOME_COMPLETO AS MEDICO,
    E.NOME AS ESPECIALIDADE,
    C.DATA_CONSULTA
FROM CONSULTA C
JOIN UTENTE U ON U.ID_UTENTE = C.ID_UTENTE
JOIN MEDICO M ON M.ID_MEDICO = C.ID_MEDICO
JOIN ESPECIALIDADE E ON E.ID_ESPECIALIDADE = C.ID_ESPECIALIDADE
WHERE C.ESTADO = 'REALIZADA'
ORDER BY C.DATA_CONSULTA DESC;

-- 30. Verificar os objectos criados no schema.
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_NAME LIKE '%'
  AND OBJECT_TYPE IN ('TABLE','VIEW','SEQUENCE','TRIGGER','INDEX')
ORDER BY OBJECT_TYPE, OBJECT_NAME;
